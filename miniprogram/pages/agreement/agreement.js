Page({
  data: { title: '', paras: [], showDelete: false, acting: false },
  onLoad(options) {
    const doc = DOCS[options.type] || DOCS.user
    // 运营主体声明:协议缺主体名称在纠纷时效力存疑,上线前必须在 config.js 填 COMPANY_NAME
    const entity = config.COMPANY_NAME || '【运营主体名称——上线前请在 utils/config.js 的 COMPANY_NAME 填写公司全称】'
    const paras = [`本平台(小程序"${config.BRAND_NAME}")由 ${entity} 运营。客服电话:${config.SERVICE_PHONE}。`].concat(doc.paras)
    // 删除申请入口只在隐私说明页出现
    this.setData({ title: doc.title, paras, showDelete: options.type === 'privacy' })
    wx.setNavigationBarTitle({ title: doc.title })
  },

  // 申请删除账号数据:云函数幂等记录,管理后台人工处理并留痕
  requestDeletion() {
    wx.showModal({
      title: '申请删除账号数据',
      content: '提交后平台将在15个工作日内处理:清除你的手机号、地址、照片等个人信息。进行中的订单与未完结投诉会先处理完。确定提交吗?',
      confirmText: '提交申请',
      success: async (r) => {
        if (!r.confirm) return
        this.setData({ acting: true })
        try {
          const res = await callFn('requestDeletion', {})
          wx.showModal({
            title: res.already ? '申请已在处理中' : '申请已提交',
            content: res.already
              ? '你之前提交的删除申请正在处理,无需重复提交。如有疑问可致电客服。'
 : '平台将在15个工作日内处理并通过订单预留电话与你确认。',
            showCancel: false
          })
        } catch (e) { /* callFn 已提示 */ } finally {
          this.setData({ acting: false })
        }
      }
    })
  }
})
